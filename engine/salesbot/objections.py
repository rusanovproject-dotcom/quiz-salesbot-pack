"""objections.py — карта возражений: текст человека → тег → указание, как себя вести.

Классификатор грубый, по словам-маркерам. Этого достаточно: точность тут не нужна,
нужна скорость реакции и правильная ветка. Опасное (агрессия, обвинение в разводе)
проверяется первым, чтобы «уже есть чатгпт, развод какой-то» ушло в эскалацию,
а не потерялось в бытовом возражении.
"""
from __future__ import annotations

_MARKERS = {
    "AGGRO":       ("тупая", "тупой", "пошёл на", "отвали", "достал", "бесишь", "заткнись"),
    "DISTRUST":    ("развод", "не верю", "обман", "лохотрон", "впариваешь", "скам", "мошен"),
    "ARE_YOU_BOT": ("ты бот", "это бот", "ты робот", "ты живой", "с живым", "живой человек"),
    "GUARANTEES":  ("гаранти", "а вдруг не", "если не получится", "вернёте деньги", "вернёшь деньги"),
    "PRICE":       ("дорого", "дороговато", "нет денег", "дешевле", "много за", "не потяну"),
    "LATER":       ("потом", "позже", "подумаю", "не сейчас", "как-нибудь", "не готов сейчас"),
    "DIY":         ("сам справлюсь", "сам сделаю", "и так всё делаю", "мне не нужно", "сам пишу"),
}

# Порядок = приоритет. Опасные первыми.
_PRIORITY = ["AGGRO", "DISTRUST", "ARE_YOU_BOT", "GUARANTEES", "PRICE", "LATER", "DIY"]

# Указания модели. Формулировки под свою нишу правь здесь — но логику веток не ломай.
_DIRECTIVES = {
    "PRICE":
        "Не оправдывайся и не сбивай цену. Переверни на то, во что ему обходится нынешнее "
        "положение. Скажи один раз, не дави дважды.",
    "LATER":
        "Честно отпусти: «ок, тогда вот бесплатное, вернёшься — я тут». Не дожимай.",
    "DIY":
        "Не спорь, что он не справится. Разведи: одно дело делать руками, другое — чтобы "
        "работало без тебя. Покажи разницу на его же процессе.",
    "ARE_YOU_BOT":
        "Правду в лоб, без вранья: ты ИИ-версия, собранная владельцем. Живого можно поймать "
        "там-то. Раздвоение не маскируй, оно часть силы.",
    "DISTRUST":
        "Не убеждай словами. Честность плюс конкретика его случая. Жёстко — эскалируй.",
    "GUARANTEES":
        "Только факты из конфига. Гарантию результата НЕ давать ни в какой форме.",
    "AGGRO":
        "Не отшучивайся и не груби в ответ. Эскалация к живому человеку.",
}


def classify(text: str) -> str | None:
    t = (text or "").lower()
    for tag in _PRIORITY:
        if any(m in t for m in _MARKERS[tag]):
            return tag
    return None


def directive(tag: str) -> str:
    return _DIRECTIVES.get(tag, "")


def should_escalate(tag: str) -> bool:
    return tag in ("AGGRO", "DISTRUST")
