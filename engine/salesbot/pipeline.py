"""pipeline.py — машина шагов разбора. Чистые функции, без сети и файлов.

Главный принцип: КОД решает, какой сейчас шаг. МОДЕЛЬ пишет текст этого шага.
Отдашь выбор шага модели — она начнёт продавать на первом сообщении.

Шаги:
  REVIEW       разбор по ответам квиза. Первое сообщение, самое важное
  DIRECT_Q     вопрос в лоб: чего хочет на самом деле
  DEEPEN       углубление, максимум два раза подряд
  FEEDBACK     мясо: связка, первый шаг, где деньги
  BRIDGE       мост на бесплатное: гайд, эфир, разбор
  PITCH        оффер по дорожке из карточки

Почему углублений максимум два: третий вопрос подряд на разогретом человеке
читается как допрос, и он уходит. Хочет ответ — дай ответ.
"""
from __future__ import annotations

DEEPEN_CAP = 2
ORDER = ["REVIEW", "DIRECT_Q", "DEEPEN", "FEEDBACK", "BRIDGE", "PITCH"]

# Человек сам заговорил о покупке.
# Маркеры узкие намеренно: «сколько это займёт» — вопрос про сроки, а не про деньги,
# и на нём нельзя выпрыгивать в оффер посреди разбора
_BUY_MARKERS = ("запиши меня", "записаться", "сколько стоит", "какая цена", "что по цене",
                "беру", "оплат", "купить", "хочу взять", "куда платить", "как платить")

# Хочет ответ, а не ещё вопрос. Стоп углублять, выдавай мясо
_READY_MARKERS = ("как сделать", "как собрать", "как это", "как именно", "как работает",
                  "с чего начать", "где деньг", "что дальше", "а дальше", "что предлаг",
                  "что по итогу", "что делать", "покажи", "под меня")

# Контексты, где слово о покупке — на самом деле НЕ покупка.
# «уже оплатил кучу курсов», «не беру» — это недоверие и прошлый опыт
_NOT_BUY_CTX = ("не ", "развод", "уже оплат", "уже куп", "напокупал", "не хочу", "не буду")

# Сошёл со скрипта: встречный вопрос, сомнение, односложка
_HOLD_QWORDS = ("кто ты", "ты сам", "а почему", "а это", "законно", "а как ты", "а зачем")


def maybe_shortcut(user_text: str, step: str) -> str | None:
    """Перепрыгнуть шаг, если человек сам туда пришёл. Иначе None.

    На входе (REVIEW и DIRECT_Q) не шорткатим: человек ещё не разогрет,
    ранний оффер — самый частый способ потерять тёплого.
    """
    t = (user_text or "").lower()
    if step == "PITCH":
        return None
    if step in ("DIRECT_Q", "DEEPEN") and any(m in t for m in _READY_MARKERS):
        return "FEEDBACK"
    if step in ("REVIEW", "DIRECT_Q"):
        return None
    if any(c in t for c in _NOT_BUY_CTX):
        return None
    if any(m in t for m in _BUY_MARKERS):
        return "PITCH"
    return None


def should_hold(user_text: str) -> bool:
    """Не двигать шаг: человек задал встречный вопрос, оспорил или ответил односложно.

    Это граница, где жёсткая машина убивает живость. Тащить дальше по сценарию
    того, кто спросил «а ты вообще кто» — верный способ получить в ответ тишину.
    """
    t = (user_text or "").strip().lower()
    if "?" in t and not any(m in t for m in _BUY_MARKERS):
        return True
    if any(q in t for q in _HOLD_QWORDS):
        return True
    if len(t.split()) <= 2:
        return True
    if t.startswith(("да фигня", "не так", "неправда", "это не про", "ты не понял")):
        return True
    return False


def next_step(step: str, deepen: int) -> tuple[str, int]:
    """Следующий шаг и счётчик углублений."""
    if step == "REVIEW":
        return ("DIRECT_Q", deepen)
    if step == "DIRECT_Q":
        return ("DEEPEN", deepen + 1)
    if step == "DEEPEN":
        return ("DEEPEN", deepen + 1) if deepen < DEEPEN_CAP else ("FEEDBACK", deepen)
    if step == "FEEDBACK":
        return ("BRIDGE", deepen)
    if step == "BRIDGE":
        return ("PITCH", deepen)
    return ("PITCH", deepen)


